"""Generate the case-workbook reference tables from the HydroPol2D input catalog.

The MATLAB repository builds HydroPol2D_Inputs.xlsx from
tools/workbook_builder/input_catalog.yaml. This script turns the same catalog into the
English reference on two pages, between generated-content markers:

- docs/configuration/general_data.md: every setting, tab by tab and block by block;
- docs/configuration/flags.md: every switch.

Run from the docs repository root:

    python3 tools/case_workbook_reference.py /path/to/HydroPol2D/tools/workbook_builder/input_catalog.yaml

The pt and es pages are translated by hand from the English output; rerunning this
script does not touch them.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    "settings": ROOT / "docs/configuration/general_data.md",
    "switches": ROOT / "docs/configuration/flags.md",
}
BEGIN = "{/* BEGIN generated by tools/case_workbook_reference.py: NAME */}"
END = "{/* END generated: NAME */}"

# Workbook notes still name the older files; point them at the case-workbook tabs.
RENAMES = [
    (r"Settings are in the Layered Subsurface block of General_Data \(D10:F28\) and the optional rasters T21:T28\.",
     "Settings are in the layered-subsurface blocks of the Soil and groundwater tab; the optional rasters sit under the values they override."),
    (r"Heads are in the Feddes block of General_Data \(D30:F36\)\.", "Heads are in this block."),
    (r"\bthe Satellite or Radar Rainfall table in General_Data\b", "the Rainfall maps list"),
    (r"\bfrom General_Data\b", "from the Rain and ET tab"),
    (r"\blisted in General_Data\b", "listed in the gauge table"),
    (r"\bVoronoi_Settings\.xlsx\b", "the Mesh tab"),
    (r"\bInflow_Hydrograph\.xlsx\b", "the Inflow hydrographs tab"),
    (r"\bStage_Hydrograph\.xlsx\b", "the Stage hydrographs tab"),
    (r"\bLULC_parameters\.xlsx\b", "the Land use classes tab"),
    (r"\bSOIL_parameters\.xlsx\b", "the Soil classes tab"),
    (r"\bhuman_risk\.xlsx\b", "the Human instability tab"),
    (r"\bBC_Control_structure\.xlsx\b", "the Control structures tab"),
    (r"\bRainfall_Intensity_Data\.xlsx\b", "the Rain series tab"),
    (r"\bRainfall_Spatial_Input\.xlsx\b", "the Rain gauges tab"),
    (r"\bETP_input_data\.xlsx\b", "the Climate stations tab"),
]


def slug(text: str) -> str:
    text = re.sub(r"[^\w\s-]", "", text.lower())
    return re.sub(r"[\s_]+", "-", text).strip("-")


def cell(text) -> str:
    """Text safe inside an MDX table cell."""
    s = "" if text is None else str(text)
    for pattern, new in RENAMES:
        s = re.sub(pattern, new, s)
    s = " ".join(s.split())
    s = s.replace("|", "\\|").replace("$", "\\$")
    s = s.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace(">", "&gt;")
    return s


def default(value) -> str:
    if value in (None, "required"):
        return "required"
    if value == "":
        return "empty"
    return f"`{value}`"


def block_switch(block) -> str | None:
    if block.get("switch"):
        return block["switch"]
    first = block["inputs"][0] if block["inputs"] else None
    if first and first["kind"] == "switch" and str(first.get("used_when", "")).startswith("switch"):
        return first["key"]
    return None


def settings(catalog) -> str:
    out = []
    for tab in catalog["tabs"]:
        out.append(f"### {tab['name']} {{#tab-{slug(tab['name'])}}}\n")
        out.append(f"{cell(tab.get('purpose'))}\n")
        for block in tab["blocks"]:
            out.append(f"#### {cell(block['title'])}\n")
            switch = block_switch(block)
            if switch:
                out.append(f"Switch: `{switch}`. The rest of the block greys out while it is 0.\n")
            elif block.get("controlled_by"):
                out.append(f"Greyed out while `{block['controlled_by']}` is 0.\n")
            out.append("| Setting | Key | Unit | Default | Used when | Description |")
            out.append("|---|---|---|---|---|---|")
            for i in block["inputs"]:
                out.append(
                    f"| {cell(i['label'])} | `{i['key']}` | {cell(i['unit'])} | {default(i.get('default'))} "
                    f"| {cell(i.get('used_when'))} | {cell(i.get('note'))} |"
                )
            out.append("")
    return "\n".join(out)


def switches(catalog) -> str:
    out = []
    for tab in catalog["tabs"]:
        rows = [(b, i) for b in tab["blocks"] for i in b["inputs"] if i["kind"] == "switch" or str(i["unit"]).startswith("0 /")]
        if not rows:
            continue
        out.append(f"### {tab['name']} {{#switches-{slug(tab['name'])}}}\n")
        out.append("| Switch | Block | Values | Default | Description |")
        out.append("|---|---|---|---|---|")
        for block, i in rows:
            out.append(
                f"| `{i['key']}` | {cell(block['title'])} | {cell(i['unit'])} | {default(i.get('default'))} | {cell(i.get('note'))} |"
            )
        out.append("")
    return "\n".join(out)


def splice(page: Path, name: str, body: str) -> None:
    text = page.read_text()
    begin, end = BEGIN.replace("NAME", name), END.replace("NAME", name)
    if begin not in text or end not in text:
        raise SystemExit(f"{page}: missing markers for '{name}'")
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    page.write_text(f"{head}{begin}\n\n{body}\n{end}{tail}")
    print(f"updated {page.relative_to(ROOT)} ({name})")


def main() -> None:
    catalog = yaml.safe_load(Path(sys.argv[1]).read_text())
    splice(PAGES["settings"], "settings", settings(catalog))
    splice(PAGES["switches"], "switches", switches(catalog))


if __name__ == "__main__":
    main()
